#!/usr/bin/env bash
set -e -o pipefail

if [[ -f "$PROXYCHAINS_CONF_FILE" ]]; then
    proxychains4-daemon -i 127.0.0.1 -p 1053 &
    disown -h
    LD_PRELOAD="/usr/lib/x86_64-linux-gnu/libproxychains.so.4"
    export LD_PRELOAD
fi

if [[ "$EUID" -eq 0 ]]; then
    cat <<EOF > /etc/profile.d/env-ai-agents.sh
#!/usr/bin/env bash

AI_API_URL="${AI_API_URL}"
AI_API_KEY="${AI_API_KEY}"
AI_CONTEXT_LENGTH="${AI_CONTEXT_LENGTH}"
AI_MODEL="${AI_MODEL}"
AI_CHEAP_MODEL="${AI_CHEAP_MODEL}"
AI_DECIDER_MODEL="${AI_DECIDER_MODEL}"
AI_VISION_MODEL="${AI_VISION_MODEL}"
AI_NAME="${AI_NAME}"
AI_REQUEST_TIMEOUT="${AI_REQUEST_TIMEOUT}"
HERMES_TUI_DIR="${HERMES_TUI_DIR}"
LD_PRELOAD="${LD_PRELOAD}"
OPENCODE_CONFIG="${OPENCODE_CONFIG}"
PROXYCHAINS_CONF_FILE="${PROXYCHAINS_CONF_FILE}"
PROXYCHAINS_QUIET_MODE="${PROXYCHAINS_QUIET_MODE}"

export AI_API_URL AI_API_KEY AI_CONTEXT_LENGTH AI_MODEL AI_CHEAP_MODEL AI_DECIDER_MODEL \
    AI_VISION_MODEL AI_NAME AI_REQUEST_TIMEOUT HERMES_TUI_DIR LD_PRELOAD OPENCODE_CONFIG \
    PROXYCHAINS_CONF_FILE PROXYCHAINS_QUIET_MODE
EOF
fi


exec entrypoint-desktop.sh "$@"
